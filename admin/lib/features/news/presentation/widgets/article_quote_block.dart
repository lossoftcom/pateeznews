class ArticleQuoteBlockEntry {
  ArticleQuoteBlockEntry()
    : authorController = TextEditingController(),
      sourceController = TextEditingController(),
      quoteController = quill.QuillController(
        document: adminQuillDocumentFromJson(adminEmptyQuillDeltaJson),
        selection: const TextSelection.collapsed(offset: 0),
      );

  final TextEditingController authorController;
  final TextEditingController sourceController;
  final quill.QuillController quoteController;
  var showOnHomepage = false;
  var extraSettingsExpanded = false;

  void dispose() {
    authorController.dispose();
    sourceController.dispose();
    quoteController.dispose();
  }
}

